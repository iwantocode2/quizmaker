
<?php
require_once __DIR__ . '/connect.php';
require_once __DIR__ . '/auth.php';

require_login_json();

if (!file_exists(__DIR__ . '/config.php')) {
    json_response(500, [
        'success' => false,
        'message' => 'Copy config.example.php to config.php and add your Gemini API key.'
    ]);
}

require_once __DIR__ . '/config.php';

if (
    !defined('GEMINI_API_KEY') ||
    !GEMINI_API_KEY ||
    strpos(GEMINI_API_KEY, 'PASTE_') === 0
) {
    json_response(500, [
        'success' => false,
        'message' => 'Add your Gemini API key to config.php.'
    ]);
}

if (!defined('GEMINI_MODEL') || !GEMINI_MODEL) {
    json_response(500, [
        'success' => false,
        'message' => 'Set GEMINI_MODEL in config.php to a model ID available to your API key.'
    ]);
}

if (!function_exists('curl_init')) {
    json_response(500, [
        'success' => false,
        'message' => 'PHP cURL is not enabled on this hosting account.'
    ]);
}

$data = json_decode(file_get_contents('php://input'), true) ?? [];

$topic = trim((string)($data['topic'] ?? ''));
$count = (int)($data['count'] ?? 5);

if (
    $topic === '' ||
    strlen($topic) > 300 ||
    !in_array($count, [5, 10, 15], true)
) {
    json_response(400, [
        'success' => false,
        'message' => 'Enter a topic under 300 characters and choose 5, 10, or 15 questions.'
    ]);
}

$prompt = "Create exactly $count multiple-choice quiz questions about: $topic.
Return ONLY valid JSON in this schema:
{\"questions\":[{\"text\":\"question\",\"answers\":{\"A\":\"...\",\"B\":\"...\",\"C\":\"...\",\"D\":\"...\"},\"correct\":\"A\"}]}.
Each question must have four answer choices. The correct field must be A, B, C, or D.
Avoid markdown. Do not include any text outside the JSON.";

$payload = [
    'contents' => [
        [
            'parts' => [
                ['text' => $prompt]
            ]
        ]
    ],
    'generationConfig' => [
        'responseMimeType' => 'application/json',
        'temperature' => 0.4
    ]
];

$url = 'https://generativelanguage.googleapis.com/v1beta/models/'
    . rawurlencode(GEMINI_MODEL)
    . ':generateContent?key='
    . rawurlencode(GEMINI_API_KEY);

$ch = curl_init($url);

curl_setopt_array($ch, [
    CURLOPT_POST => true,
    CURLOPT_RETURNTRANSFER => true,
    CURLOPT_HTTPHEADER => [
        'Content-Type: application/json'
    ],
    CURLOPT_POSTFIELDS => json_encode($payload),
    CURLOPT_CONNECTTIMEOUT => 15,
    CURLOPT_TIMEOUT => 45
]);

$out = curl_exec($ch);
$status = (int) curl_getinfo($ch, CURLINFO_HTTP_CODE);
$curlError = curl_error($ch);

curl_close($ch);

/* Show connection errors instead of a generic Gemini error. */
if ($out === false) {
    error_log('Gemini cURL error: ' . $curlError);

    json_response(502, [
        'success' => false,
        'message' => 'Connection error: ' . $curlError
    ]);
}

/* Show Google's actual HTTP error message. */
if ($status < 200 || $status >= 300) {
    $apiError = json_decode($out, true);
    $details = $apiError['error']['message']
        ?? 'Google returned an HTTP error without a readable message.';

    error_log('Gemini HTTP ' . $status . ': ' . $details);

    json_response(502, [
        'success' => false,
        'message' => 'Gemini HTTP ' . $status . ': ' . $details
    ]);
}

/* Decode Google's successful response. */
$decoded = json_decode($out, true);

if (!is_array($decoded)) {
    json_response(502, [
        'success' => false,
        'message' => 'Gemini returned invalid JSON. Try again.'
    ]);
}

if (!empty($decoded['promptFeedback']['blockReason'])) {
    json_response(502, [
        'success' => false,
        'message' => 'Gemini blocked this request: '
            . $decoded['promptFeedback']['blockReason']
    ]);
}

$text = $decoded['candidates'][0]['content']['parts'][0]['text'] ?? '';

if ($text === '') {
    $finishReason = $decoded['candidates'][0]['finishReason']
        ?? 'Unknown';

    json_response(502, [
        'success' => false,
        'message' => 'Gemini returned no quiz text. Finish reason: '
            . $finishReason
    ]);
}

/* Parse the JSON generated by Gemini. */
$result = json_decode($text, true);

if (!is_array($result) || !isset($result['questions'])
    || !is_array($result['questions'])) {
    json_response(502, [
        'success' => false,
        'message' => 'AI returned an unexpected format. Try again.'
    ]);
}

/* Validate each question and its four answer choices. */
$questions = [];

foreach (array_slice($result['questions'], 0, $count) as $q) {
    if (!is_array($q)) {
        continue;
    }

    $questionText = trim((string)($q['text'] ?? ''));
    $answers = $q['answers'] ?? [];
    $correct = strtoupper(trim((string)($q['correct'] ?? '')));

    if (
        $questionText === '' ||
        !in_array($correct, ['A', 'B', 'C', 'D'], true) ||
        !is_array($answers)
    ) {
        continue;
    }

    $cleanAnswers = [];

    foreach (['A', 'B', 'C', 'D'] as $letter) {
        $answer = trim((string)($answers[$letter] ?? ''));

        if ($answer === '') {
            continue 2;
        }

        $cleanAnswers[$letter] = $answer;
    }

    $questions[] = [
        'text' => $questionText,
        'answers' => $cleanAnswers,
        'correct' => $correct
    ];
}

if (count($questions) < 1) {
    json_response(502, [
        'success' => false,
        'message' => 'AI did not return usable questions. Try a more specific topic.'
    ]);
}

json_response(200, [
    'success' => true,
    'questions' => $questions
]);
